// classifier.h - on-board elevator classifier (MIE1050 Part 4)
//
// Plain C++ with no Arduino calls, so the exact same code also compiles on a PC: Classifier/board_check/
// replays the recorded sessions through it and compares the results with Python (postprocess.py).
//
// What it does, one fast sample (200 Hz) at a time:
//   1. Stores the accelerometer and light readings in a 48 s ring buffer.
//   2. Every 0.1 s turns the latest pressure into altitude, smooths it over 1.5 s and differentiates it.
//      A ride = the car moving faster than 0.3 m/s (the same rules as postprocess.py).
//   3. 6 s after a ride ends, computes the two features over the buffered ride:
//        launch jerk   - slope of the launch acceleration ramp (g/s)
//        light flicker - strength of the lamp ripple relative to the light level
//      and classifies them with KNN (K = 15) against the training rides in knn_model.h.
//   4. Cross-check: flicker alone says which pair the ride belongs to (Hart House / MC = no flicker,
//      Myhal / Rosebrugh = flicker), and jerk alone picks the building with the nearest median jerk.
//      If jerk's pick is in the other pair, the two sensors disagree and the result is flagged.

#pragma once
#include <math.h>
#include <stdint.h>
#include <algorithm>
#include "knn_model.h"   // generated by Classifier/elevator_classifier.ipynb

namespace ride {

//------------------ settings (the same numbers as postprocess.py) ------------------
const float FS = 200.0f;                // fast sample rate, Hz
const int BUF_N = 9600;                 // ring buffer length: 48 s (longest ride ~31 s, plus margins)
const float ACCEL_SCALE = 8192.0f;      // accel stored as int16 in 1/8192 g (finer than the sensor's 1/1024 g)

// ride detection from the barometer
const float PA_PER_M = 12.0f;           // ~12 Pa of pressure per metre of height
const int GRID_STEP = 20;               // altitude sampled every 20 fast samples = 0.1 s
const float GRID_DT = 0.1f;
const int SMOOTH_N = 15;                // altitude smoothed over 15 grid points = 1.5 s
const float SPEED_ON = 0.30f;           // m/s; the car counts as moving above this
const int MERGE_GAP = 20;               // a pause of up to 20 grid points (2 s) does not end a ride
const float MIN_RIDE_S = 2.0f;          // ignore "rides" shorter than 2 s ...
const float MIN_RIDE_M = 1.0f;          // ... or smaller than 1 m

// features
const int PHASE_SEARCH = 600;           // look 3 s either side of the barometer's ride for the launch / brake peaks
const float MOTION_FRAC = 0.10f;        // motion starts / ends where |accel| crosses 10% of the peak
const float MIN_PHASE_ACCEL = 0.01f;    // g; launch and brake peaks must both reach this
const int STILL = 200;                  // 1 s
const int PRE = 1000;                   // keep 5 s before the ride (3 s search + 2 s for the filter to settle)
const int POST = 1200;                  // classify 6 s after the ride (3 s search + 1 s still + 2 s filter)
const int NPERSEG = 256;                // flicker spectrum: 256-sample (1.28 s) segments, half overlapping
const float FLICKER_LO = 50.0f;         // Hz; search band for the lamp ripple (120 Hz shows at 80 Hz at 200 Hz sampling)
const float FLICKER_HI = 99.0f;
const float TWO_PI_F = 6.28318531f;     // (Arduino already defines TWO_PI as a macro, hence the _F)

// 4th-order Butterworth low-pass at 1.5 Hz (fs = 200 Hz) as two biquad sections [b0 b1 b2 a0 a1 a2],
// from scipy.signal.butter(4, 1.5, fs=200, output="sos"). Run forward then backward = zero phase.
const double SOS[2][6] = {
    {2.9001703358711944e-07, 5.800340671742389e-07, 2.9001703358711944e-07, 1.0, -1.9144610905921862, 0.9165887437442231},
    {1.0, 2.0, 1.0, 1.0, -1.9624037752498193, 0.9645847099256387},
};

struct Result {
  bool valid;            // false = the ride was not classified; `why` says the reason
  const char* why;       // "" when valid
  int building;          // index into knn::CLASS_NAMES
  float launchJerk;      // g/s
  float flicker;         // light flicker index
  bool agree;            // cross-check passed: jerk's nearest building is in flicker's pair
  bool up;               // direction from the barometer
  uint32_t startSample;  // motion start / end, counted in samples since boot
  uint32_t endSample;
};

class RideClassifier {
 public:
  // Call once per fast sample. pres = NAN unless a new pressure reading (Pa) arrived with this sample.
  // Returns true when a ride has just been classified; the answer is then in result().
  bool addSample(float ax, float ay, float az, int16_t light, float pres) {
    // 1. store the sample (a failed accel read repeats the previous value)
    int slot = n_ % BUF_N;
    int prev = (n_ + BUF_N - 1) % BUF_N;
    ax_[slot] = isnan(ax) ? ax_[prev] : (int16_t)lrintf(ax * ACCEL_SCALE);
    ay_[slot] = isnan(ay) ? ay_[prev] : (int16_t)lrintf(ay * ACCEL_SCALE);
    az_[slot] = isnan(az) ? az_[prev] : (int16_t)lrintf(az * ACCEL_SCALE);
    light_[slot] = light;

    // 2. altitude every 0.1 s -> smoothed altitude -> vertical speed -> ride start / end.
    // Pressure arrives at ~40 Hz, so when a new reading comes in, the 0.1 s grid points since the previous
    // reading are filled in by straight-line interpolation between the two (as np.interp in postprocess.py).
    if (!isnan(pres)) {
      if (isnan(lastPres_)) {
        presRef_ = pres;                                    // altitude is measured from the first reading
        nextGrid_ = (n_ + GRID_STEP - 1) / GRID_STEP * GRID_STEP;
      } else {
        for (; nextGrid_ <= n_; nextGrid_ += GRID_STEP) {
          float frac = (float)(nextGrid_ - lastPresSample_) / (float)(n_ - lastPresSample_);
          addGridPoint(nextGrid_, lastPres_ + frac * (pres - lastPres_));
        }
      }
      lastPres_ = pres;
      lastPresSample_ = n_;
    }
    n_++;

    // 3. classify once the buffer holds POST samples past the ride's end
    if (pending_ && n_ >= i1_ + POST) {
      pending_ = false;
      classify();
      return true;
    }
    return false;
  }

  const Result& result() const { return res_; }

 private:
  // ring buffer (static size: about 115 KB in all)
  int16_t ax_[BUF_N] = {}, ay_[BUF_N] = {}, az_[BUF_N] = {}, light_[BUF_N] = {};
  float work_[BUF_N];        // scratch space: one ride's vertical acceleration
  uint32_t n_ = 0;           // samples received so far

  // altitude grid (0.1 s)
  float lastPres_ = NAN;     // latest pressure reading (Pa) and the sample it came with
  uint32_t lastPresSample_ = 0;
  float presRef_ = 0;        // first pressure reading; altitudes are relative to it (keeps floats precise)
  uint32_t nextGrid_ = 0;    // sample number of the next 0.1 s grid point
  uint32_t g_ = 0;           // grid points so far
  float alt_[16];            // last 16 raw altitudes (m)
  uint32_t gridSample_[16];  // the sample number each grid point was taken at
  float altS_[4];            // smoothed altitude, indexed by grid point % 4

  // ride being tracked
  bool open_ = false, pending_ = false, up_ = false;
  uint32_t startGrid_ = 0, endGrid_ = 0, i0_ = 0, i1_ = 0, spanStart_ = 0, spanEnd_ = 0;
  float startAlt_ = 0, endAlt_ = 0;
  Result res_ = {};

  // One altitude grid point. The smoothing is centred (as in postprocess.py), so the speed at grid
  // point m is only known 8 points (0.8 s) later.
  void addGridPoint(uint32_t sample, float pres) {
    alt_[g_ % 16] = -(pres - presRef_) / PA_PER_M;         // metres above the first reading
    gridSample_[g_ % 16] = sample;
    g_++;
    if (g_ < SMOOTH_N) return;
    uint32_t c = g_ - 1 - SMOOTH_N / 2;                     // centre of the last 15 points
    float sum = 0;
    for (uint32_t k = g_ - SMOOTH_N; k < g_; k++) sum += alt_[k % 16];
    altS_[c % 4] = sum / SMOOTH_N;
    if (c < SMOOTH_N / 2 + 2) return;                       // need smoothed values on both sides of m
    uint32_t m = c - 1;
    float speed = (altS_[c % 4] - altS_[(m - 1) % 4]) / (2 * GRID_DT);   // central difference, m/s
    trackRide(m, gridSample_[m % 16], altS_[m % 4], speed);
  }

  // Same rules as postprocess.segment_rides: moving spans closer than 2 s merge into one ride; a ride
  // must last 2 s and cover 1 m.
  void trackRide(uint32_t m, uint32_t sample, float alt, float speed) {
    if (fabsf(speed) > SPEED_ON) {
      if (!open_) {
        open_ = true;
        startGrid_ = m; spanStart_ = sample; startAlt_ = alt;
      }
      endGrid_ = m; spanEnd_ = sample; endAlt_ = alt;
    } else if (open_ && m - endGrid_ > (uint32_t)MERGE_GAP) {
      open_ = false;
      float duration = (endGrid_ - startGrid_) * GRID_DT;
      float height = endAlt_ - startAlt_;
      if (duration >= MIN_RIDE_S && fabsf(height) >= MIN_RIDE_M) {
        pending_ = true;
        i0_ = spanStart_; i1_ = spanEnd_; up_ = height > 0;
      }
    }
  }

  //------------------ feature extraction (same steps as postprocess.ride_features) ------------------
  void classify() {
    res_ = {};
    res_.up = up_;
    res_.startSample = i0_;                                 // the barometer's span until motion is found
    res_.endSample = i1_;
    res_.why = "ride too long for the buffer, or too soon after power-on";
    uint32_t oldest = n_ > (uint32_t)BUF_N ? n_ - BUF_N : 0;
    if (i0_ < oldest + PRE) return;
    uint32_t w0 = i0_ - PRE;                                // the ride's window: [w0, n_)
    int L = (int)(n_ - w0);

    // gravity = median accel over the whole buffer (dwells and cruise read exactly 1 g)
    float g[3];
    const int16_t* axes[3] = {ax_, ay_, az_};
    int count = (int)(n_ - oldest);
    for (int a = 0; a < 3; a++) g[a] = medianOf(axes[a], oldest, count) / ACCEL_SCALE;
    float gmag = sqrtf(g[0] * g[0] + g[1] * g[1] + g[2] * g[2]);

    // vertical acceleration (g, + = up), low-passed at 1.5 Hz without phase shift
    for (int k = 0; k < L; k++) {
      int s = (w0 + k) % BUF_N;
      work_[k] = (ax_[s] * g[0] + ay_[s] * g[1] + az_[s] * g[2]) / (ACCEL_SCALE * gmag) - gmag;
    }
    zeroPhaseLowPass(work_, L);
    const float* a = work_;

    // launch peak near the ride's start, brake peak near its end (signs follow the direction)
    float d = up_ ? 1.0f : -1.0f;
    int i0 = (int)(i0_ - w0), i1 = (int)(i1_ - w0);
    int kL = argmax(a, std::max(0, i0 - PHASE_SEARCH), std::min(L, i0 + PHASE_SEARCH), d);
    int kB = argmax(a, std::max(0, i1 - PHASE_SEARCH), std::min(L, i1 + PHASE_SEARCH), -d);
    res_.why = "no clear launch and brake";
    if (kB <= kL) return;
    float pkL = fabsf(a[kL]), pkB = fabsf(a[kB]);
    if (std::min(pkL, pkB) < MIN_PHASE_ACCEL) return;

    // motion start / end = where |accel| falls to 10% of the peaks
    int s = 0;
    for (int k = kL - 1; k >= 0; k--) if (fabsf(a[k]) < MOTION_FRAC * pkL) { s = k; break; }
    int e = L - 1;
    for (int k = kB; k < L; k++) if (fabsf(a[k]) < MOTION_FRAC * pkB) { e = k; break; }
    res_.why = "motion start or end outside the buffer";
    if (s < STILL || e > L - 1 - STILL) return;

    // feature 1: launch jerk = least-squares slope of |accel| over the 20-80% part of the launch ramp
    double n = 0, st = 0, sy = 0, stt = 0, sty = 0;
    for (int k = s; k <= kL; k++) {
      float y = fabsf(a[k]);
      if (y < 0.2f * pkL || y > 0.8f * pkL) continue;
      double t = (k - s) / FS;
      n++; st += t; sy += y; stt += t * t; sty += t * y;
    }
    res_.why = "launch ramp too short to fit";
    if (n < 5) return;
    res_.launchJerk = (float)fabs((n * sty - st * sy) / (n * stt - st * st));

    // feature 2: light flicker over the motion span
    res_.flicker = flickerIndex(w0 + s, e - s + 1);

    res_.valid = true;
    res_.why = "";
    res_.startSample = w0 + s;
    res_.endSample = w0 + e;
    res_.building = knnPredict(res_.launchJerk, res_.flicker);
    res_.agree = crossCheck(res_.launchJerk, res_.flicker);
  }

  static int argmax(const float* a, int lo, int hi, float sign) {
    int best = lo;
    for (int k = lo + 1; k < hi; k++) if (sign * a[k] > sign * a[best]) best = k;
    return best;
  }

  // Median of `count` ring-buffer values starting at sample `first` (uses work_ as scratch).
  float medianOf(const int16_t* buf, uint32_t first, int count) {
    for (int k = 0; k < count; k++) work_[k] = buf[(first + k) % BUF_N];
    int mid = count / 2;
    std::nth_element(work_, work_ + mid, work_ + count);
    float hi = work_[mid];
    if (count % 2) return hi;
    float lo = *std::max_element(work_, work_ + mid);       // even count: average the two middle values
    return 0.5f * (lo + hi);
  }

  // Butterworth low-pass run forward then backward (like scipy's sosfiltfilt), in place.
  static void zeroPhaseLowPass(float* x, int L) {
    for (int pass = 0; pass < 2; pass++) {
      double z[2][2] = {{0, 0}, {0, 0}};                    // filter state per section
      for (int i = 0; i < L; i++) {
        int k = pass == 0 ? i : L - 1 - i;                   // second pass runs backwards
        double v = x[k];
        for (int sec = 0; sec < 2; sec++) {
          const double* c = SOS[sec];
          double y = c[0] * v + z[sec][0];
          z[sec][0] = c[1] * v - c[4] * y + z[sec][1];
          z[sec][1] = c[2] * v - c[5] * y;
          v = y;
        }
        x[k] = (float)v;
      }
    }
  }

  // Lamp-ripple strength: Welch power spectrum of the light signal (256-sample Hann segments, 50%
  // overlap, as scipy.signal.welch), find the strongest tone in 50-99 Hz, take its amplitude and divide
  // by the mean light level. No flicker -> 0.
  float flickerIndex(uint32_t first, int count) {
    if (count < NPERSEG) return 0;
    static float re[NPERSEG], im[NPERSEG], win[NPERSEG];
    static double P[NPERSEG / 2 + 1];
    double winSq = 0;
    for (int k = 0; k < NPERSEG; k++) {
      win[k] = 0.5f - 0.5f * cosf(TWO_PI_F * k / NPERSEG);
      winSq += (double)win[k] * win[k];
    }
    for (int k = 0; k <= NPERSEG / 2; k++) P[k] = 0;

    int step = NPERSEG / 2;
    int nseg = (count - step) / step;
    for (int sgm = 0; sgm < nseg; sgm++) {
      uint32_t start = first + sgm * step;
      double mean = 0;
      for (int k = 0; k < NPERSEG; k++) mean += light_[(start + k) % BUF_N];
      mean /= NPERSEG;
      for (int k = 0; k < NPERSEG; k++) {
        re[k] = (float)(light_[(start + k) % BUF_N] - mean) * win[k];   // remove the mean, then window
        im[k] = 0;
      }
      fft(re, im, NPERSEG);
      for (int k = 0; k <= NPERSEG / 2; k++) P[k] += (double)re[k] * re[k] + (double)im[k] * im[k];
    }
    double scale = 1.0 / (FS * winSq * nseg);               // power spectral density, averaged over segments
    for (int k = 0; k <= NPERSEG / 2; k++) P[k] *= (k == 0 || k == NPERSEG / 2) ? scale : 2 * scale;

    double df = FS / NPERSEG;                               // 0.78 Hz per bin
    int kLo = (int)ceil(FLICKER_LO / df), kHi = (int)floor(FLICKER_HI / df);
    int kPk = kLo;
    for (int k = kLo + 1; k <= kHi; k++) if (P[k] > P[kPk]) kPk = k;
    // power within +/-0.8 Hz of the peak = the peak bin and its two neighbours (trapezoid rule)
    double bandPower = df * (0.5 * P[kPk - 1] + P[kPk] + 0.5 * P[kPk + 1]);

    double lightMean = 0;
    for (int k = 0; k < count; k++) lightMean += light_[(first + k) % BUF_N];
    lightMean /= count;
    return lightMean > 0 ? (float)(sqrt(2 * bandPower) / lightMean) : 0;
  }

  // In-place radix-2 FFT (n a power of two).
  static void fft(float* re, float* im, int n) {
    for (int i = 1, j = 0; i < n; i++) {                    // bit-reversal reordering
      int bit = n >> 1;
      for (; j & bit; bit >>= 1) j ^= bit;
      j ^= bit;
      if (i < j) { std::swap(re[i], re[j]); std::swap(im[i], im[j]); }
    }
    for (int len = 2; len <= n; len <<= 1) {                // butterflies
      float ang = -TWO_PI_F / len;
      for (int i = 0; i < n; i += len) {
        for (int k = 0; k < len / 2; k++) {
          float wr = cosf(ang * k), wi = sinf(ang * k);
          int p = i + k, q = i + k + len / 2;
          float xr = re[q] * wr - im[q] * wi, xi = re[q] * wi + im[q] * wr;
          re[q] = re[p] - xr; im[q] = im[p] - xi;
          re[p] += xr; im[p] += xi;
        }
      }
    }
  }

  //------------------ classifier ------------------
  // KNN: scale both features to 0-1 with the training min / max, find the K nearest training rides,
  // and return the most common building among them (ties -> the first building in alphabetical order).
  static int knnPredict(float jerk, float flicker) {
    float q[2] = {jerk, flicker};
    for (int f = 0; f < 2; f++) q[f] = (q[f] - knn::FEATURE_MIN[f]) / (knn::FEATURE_MAX[f] - knn::FEATURE_MIN[f]);

    float bestD[knn::K];
    int bestY[knn::K];
    int found = 0;
    for (int i = 0; i < knn::N_TRAIN; i++) {
      float d = 0;
      for (int f = 0; f < 2; f++) {
        float x = (knn::TRAIN_X[i][f] - knn::FEATURE_MIN[f]) / (knn::FEATURE_MAX[f] - knn::FEATURE_MIN[f]);
        d += (x - q[f]) * (x - q[f]);
      }
      // keep the K smallest distances, sorted (insertion)
      int pos = found < knn::K ? found++ : knn::K;
      if (pos == knn::K && d >= bestD[knn::K - 1]) continue;
      if (pos == knn::K) pos = knn::K - 1;
      while (pos > 0 && bestD[pos - 1] > d) { bestD[pos] = bestD[pos - 1]; bestY[pos] = bestY[pos - 1]; pos--; }
      bestD[pos] = d; bestY[pos] = knn::TRAIN_Y[i];
    }
    int votes[knn::N_CLASSES] = {0};
    for (int k = 0; k < found; k++) votes[bestY[k]]++;
    int best = 0;
    for (int c = 1; c < knn::N_CLASSES; c++) if (votes[c] > votes[best]) best = c;
    return best;
  }

  // Does jerk on its own point to a building in the pair that flicker says?
  static bool crossCheck(float jerk, float flicker) {
    bool flickerSaysLit = flicker > knn::FLICKER_THRESHOLD;
    int jerkPick = 0;
    for (int c = 1; c < knn::N_CLASSES; c++)
      if (fabsf(jerk - knn::CLASS_MEDIAN_JERK[c]) < fabsf(jerk - knn::CLASS_MEDIAN_JERK[jerkPick])) jerkPick = c;
    return knn::CLASS_HAS_FLICKER[jerkPick] == flickerSaysLit;
  }
};

}  // namespace ride
